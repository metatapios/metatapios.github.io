#!/usr/bin/env python3
"""Produce compact printable PDF of the 100-particle 60-day comparison.

Requires reportlab; input figures generated by tools/compare_60d.py.
"""
import argparse
from pathlib import Path
from reportlab.lib import colors
from reportlab.lib.pagesizes import A4
from reportlab.lib.styles import getSampleStyleSheet, ParagraphStyle
from reportlab.lib.enums import TA_LEFT
from reportlab.lib.units import mm
from reportlab.platypus import SimpleDocTemplate, Paragraph, Spacer, Image, PageBreak, Table, TableStyle, KeepTogether
from PIL import Image as PILImage

PLOTS = [
 ('01_survival.png', 'Survival curves: 83 impacts in the unchanged September solver; 97 in the corrected October solver by day 60.'),
 ('02_eccentricity.png', 'Osculating eccentricity histories for four matched satellite IDs. Divergence is expected because the older gravity implementation and integrator dispatch differ.'),
 ('03_altitude.png', 'Altitude above the sampled local lunar terrain. Trajectories terminate when they collide with the surface.'),
 ('04_jacobi.png', 'Running maximum Jacobi conservation error over all 100 satellites. Only lunar gravity and rigid lunar spin were enabled.'),
 ('05_node_precession.png', 'Unwrapped ascending-node longitude relative to each orbit’s starting orientation for three long-lived satellites.'),
 ('06_apsidal_precession.png', 'Projected eccentricity-vector angle (an apsidal-orientation diagnostic). Near-zero eccentricity makes this diagnostic ill-conditioned; masked intervals are not a resolved physical discontinuity.'),
 ('07_impact_locations.png', 'Body-fixed east-positive lunar impact locations of all collided satellites, using a Mollweide projection.'),
]


def run(figdir,output):
    pagesize=A4
    doc=SimpleDocTemplate(str(output),pagesize=pagesize,leftMargin=17*mm,rightMargin=17*mm,
                          topMargin=17*mm,bottomMargin=17*mm)
    st=getSampleStyleSheet()
    st.add(ParagraphStyle(name='ReportTitle',parent=st['Title'],fontSize=20,leading=25,spaceAfter=15))
    st.add(ParagraphStyle(name='ReportBody',parent=st['BodyText'],fontSize=10.5,leading=15,spaceAfter=7))
    st.add(ParagraphStyle(name='ReportCaption',parent=st['BodyText'],fontSize=10.2,leading=14,spaceAfter=6))
    flow=[]
    flow.append(Paragraph('Lunar low-orbit Monte Carlo<br/>60-day comparison of original and corrected mascons codes',st['ReportTitle']))
    flow.append(Paragraph('Experiment completed 14 October 2026 | 100 identical randomized low lunar orbits | uniform initial terrain clearance 25–50 km | harmonic degree 60 | 240 fixed steps/initial orbit | random seed 20261014 | lunar-only dynamics (no external tides / Kozai–Lidov).',st['ReportBody']))
    rows=[['Metric','September original','October corrected'],
          ['Impacts at day 30','58 / 100','78 / 100'],
          ['Impacts at day 60','83 / 100','97 / 100'],
          ['Survivors at day 60','17','3'],
          ['Median impact day','19.626','12.756'],
          ['First impact (day)','2.141','1.596'],
          ['Median max eccentricity','0.01968','0.02004'],
          ['Median relative Jacobi drift','9.61e-6','3.78e-7'],
          ['Worst relative Jacobi drift','1.38e-5','6.52e-7']]
    width=doc.width
    tbl=Table(rows,colWidths=[width*.48,width*.26,width*.26],repeatRows=1,hAlign='LEFT')
    tbl.setStyle(TableStyle([('BACKGROUND',(0,0),(-1,0),colors.HexColor('#eceff3')),
                             ('FONTSIZE',(0,0),(-1,-1),9),('BOTTOMPADDING',(0,0),(-1,-1),7),
                             ('TOPPADDING',(0,0),(-1,-1),7),('LINEBELOW',(0,0),(-1,0),.7,colors.gray),
                             ('ROWBACKGROUNDS',(0,1),(-1,-1),[colors.white,colors.HexColor('#f8f8f8')])]))
    flow.append(tbl);flow.append(Spacer(1,11*mm))
    for text in [
        '<b>Checkpoint integrity.</b> All 100 corrected particles have both latest and previous HDF5 checkpoint generations; all 97 impacts remain terminal. A 60.00 to 60.01-day restart check succeeded.',
        '<b>Paired impact locations.</b> Among the 83 satellites impacting in both versions, the median great-circle angular separation is 20.55 degrees. Another 14 crash only in the corrected version by day 60.',
        '<b>Interpretation.</b> The original code is unedited and contains gravity-normalization, integrator-dispatch, and stage-time defects. These runs do not isolate a single numerical fix. High-degree gravity, terrain-grid and timestep convergence are still required before interpreting these impact probabilities as physical predictions.',
        '<b>Availability.</b> Corrected trajectories and results are in the compressed HDF5 archive; old trajectories are in their original CSV representation. The updated code, source guide and figure-generation scripts are distributed in the separate release ZIP.'
    ]: flow.append(Paragraph(text,st['ReportBody']))
    for name,caption in PLOTS:
        flow.append(PageBreak())
        flow.append(Paragraph(name.replace('_',' ').replace('.png','').title(),st['Heading2']))
        image=PILImage.open(figdir/name)
        iw,ih=image.size
        maxw,maxh=doc.width,doc.height-38*mm
        scale=min(maxw/iw,maxh/ih)
        flow.append(Image(str(figdir/name),width=iw*scale,height=ih*scale))
        flow.append(Spacer(1,4*mm));flow.append(Paragraph(caption,st['ReportCaption']))
    def footer(canv, d):
        canv.setFont('Helvetica',8);canv.setFillColor(colors.grey)
        canv.drawString(17*mm,11*mm,'LunarMasconsOrbit  |  60-day comparison  |  14 October 2026')
        canv.drawRightString(A4[0]-17*mm,11*mm,str(d.page))
    doc.build(flow,onFirstPage=footer,onLaterPages=footer)


def main():
    a=argparse.ArgumentParser()
    a.add_argument('figure_directory',type=Path)
    a.add_argument('output_pdf',type=Path)
    c=a.parse_args();run(c.figure_directory,c.output_pdf)
if __name__=='__main__':main()
